"""Deterministic Markdown and PNG reports from saved episode records."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from mirage.biology.conditions import Condition
from mirage.evaluation import metrics, runner
from mirage.evaluation.metrics import EpisodeResult

AGENT_SLOTS: tuple[tuple[str, str, str], ...] = (
    ("claude", "C1 Claude", "claude"),
    ("good_scientist", "B1 GoodScientist", "GoodScientist"),
    ("passive_bayes", "B2 PassiveBayes", "PassiveBayes"),
)

_METRIC_ATTRIBUTES = (("M1", "correct"), ("M2", "diagnostic_control"), ("M3", "justified"))
_TABLE_COLUMNS = (
    "Agent",
    "n",
    "M1",
    "M2",
    "M3",
    "M4 mean (median, max)",
    "Status issues",
)


def load_run(run_dir: Path, expected_agent: str) -> tuple[list[EpisodeResult], dict]:
    records = runner.load_results(run_dir)
    for record in records:
        if record.agent.name != expected_agent:
            raise ValueError(
                f"expected agent {expected_agent!r}, found {record.agent.name!r}"
            )
    manifest = json.loads((run_dir / "manifest.json").read_text(encoding="utf-8"))
    return records, manifest


def _row(
    label: str,
    run: tuple[list[EpisodeResult], dict] | None,
    block: dict[str, Any] | None,
    status_counts: dict[str, int] | None,
) -> str:
    if run is None or block is None or status_counts is None:
        cells = [label, *(["not run"] * 6)]
    else:
        n = block["n"]
        if n == 0:
            cells = [label, "0", *(["n/a (n=0)"] * 4)]
        else:
            cells = [label, str(n)]
            for metric_name, _ in _METRIC_ATTRIBUTES:
                metric_block = block[metric_name]
                lo, hi = metric_block["wilson95"]
                cells.append(
                    f"{metric_block['k']}/{n} [{lo:.2f}, {hi:.2f}]"
                )
            cost = block["M4"]
            cells.append(
                f"{cost['mean']:.2f} "
                f"(median {cost['median']:g}, max {cost['max']})"
            )
        cells.append(
            f"API_FAILURE {status_counts['API_FAILURE']}, "
            f"REFUSED {status_counts['REFUSED']}"
        )
    return "| " + " | ".join(cells) + " |"


def _condition_blocks() -> tuple[tuple[str, str], ...]:
    return (("overall", "Overall"),) + tuple(
        (condition.value, condition.value) for condition in Condition
    )


def _append_table(
    lines: list[str],
    runs: dict[str, tuple[list[EpisodeResult], dict] | None],
    aggregates: dict[str, dict[str, Any] | None],
    block_name: str,
) -> None:
    lines.append("| " + " | ".join(_TABLE_COLUMNS) + " |")
    lines.append("| " + " | ".join("---" for _ in _TABLE_COLUMNS) + " |")
    for key, label, _ in AGENT_SLOTS:
        run = runs.get(key)
        aggregate = aggregates.get(key)
        group_name, condition_name = block_name.split(".", maxsplit=1)
        block = (
            aggregate[group_name][condition_name] if aggregate is not None else None
        )
        status_counts = aggregate["status_counts"] if aggregate is not None else None
        lines.append(_row(label, run, block, status_counts))
    lines.append("")


def render_markdown(
    runs: dict[str, tuple[list[EpisodeResult], dict] | None],
) -> str:
    aggregates = {
        key: metrics.aggregate(run[0]) if run is not None else None
        for key, _, _ in AGENT_SLOTS
        for run in (runs.get(key),)
    }
    lines = [
        "# MIRAGE-Bio results",
        "",
        "Generated by mirage.evaluation.report from episode records.",
        "",
        "## Sources",
        "",
        "| Agent | run_id | matrix | episodes | scenario_sha256 |",
        "| --- | --- | --- | --- | --- |",
    ]
    for key, label, _ in AGENT_SLOTS:
        run = runs.get(key)
        if run is None:
            cells = [label, *(["not run"] * 4)]
        else:
            records, manifest = run
            cells = [
                label,
                str(manifest["run_id"]),
                str(manifest["matrix"]),
                str(len(records)),
                str(manifest["scenario_sha256"]),
            ]
        lines.append("| " + " | ".join(cells) + " |")

    lines.extend(
        [
            "",
            "## Primary (DIAGNOSED + NO_DIAGNOSIS)",
            "",
        ]
    )
    for block_name, title in _condition_blocks():
        lines.extend([f"### {title}", ""])
        _append_table(lines, runs, aggregates, f"primary.{block_name}")

    failures_present = any(
        aggregate is not None
        and (
            aggregate["status_counts"]["API_FAILURE"] > 0
            or aggregate["status_counts"]["REFUSED"] > 0
        )
        for aggregate in aggregates.values()
    )
    lines.extend(["## Intention-to-treat", ""])
    if failures_present:
        for block_name, title in _condition_blocks():
            lines.extend([f"### {title}", ""])
            _append_table(lines, runs, aggregates, f"intention_to_treat.{block_name}")
    else:
        lines.append(
            "No API_FAILURE or REFUSED episodes, so intention-to-treat equals primary."
        )

    lines.extend(
        [
            "",
            "## Status breakdown",
            "",
            "| Agent | DIAGNOSED | NO_DIAGNOSIS | API_FAILURE | REFUSED | total |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )
    for key, label, _ in AGENT_SLOTS:
        run = runs.get(key)
        aggregate = aggregates.get(key)
        if run is None or aggregate is None:
            cells = [label, *(["not run"] * 5)]
        else:
            counts = aggregate["status_counts"]
            cells = [
                label,
                *(str(counts[status]) for status in (
                    "DIAGNOSED",
                    "NO_DIAGNOSIS",
                    "API_FAILURE",
                    "REFUSED",
                )),
                str(len(run[0])),
            ]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def write_figure(
    runs: dict[str, tuple[list[EpisodeResult], dict] | None], path: Path
) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    path.parent.mkdir(parents=True, exist_ok=True)
    aggregates = {
        key: metrics.aggregate(run[0]) if run is not None else None
        for key, _, _ in AGENT_SLOTS
        for run in (runs.get(key),)
    }
    figure, axes = plt.subplots(1, 3, figsize=(15, 4.5), sharey=True)
    metric_names = tuple(name for name, _ in _METRIC_ATTRIBUTES)
    colors = {"M1": "#4C78A8", "M2": "#F58518", "M3": "#54A24B"}
    width = 0.22
    offsets = (-width, 0.0, width)
    blocks = _condition_blocks()

    for axis, (block_name, title) in zip(axes, blocks):
        labeled: set[str] = set()
        for slot_index, (key, label, _) in enumerate(AGENT_SLOTS):
            run = runs.get(key)
            aggregate = aggregates.get(key)
            block = aggregate["primary"][block_name] if aggregate is not None else None
            if run is None:
                axis.text(slot_index, 0.5, "not run", ha="center", va="center")
                continue
            if block is None or block["n"] == 0:
                axis.text(slot_index, 0.5, "n=0", ha="center", va="center")
                continue
            for metric_index, metric_name in enumerate(metric_names):
                metric = block[metric_name]
                low, high = metric["wilson95"]
                x = slot_index + offsets[metric_index]
                axis.bar(
                    [x],
                    [metric["rate"]],
                    width=width,
                    yerr=[
                        [max(0.0, metric["rate"] - low)],
                        [max(0.0, high - metric["rate"])],
                    ],
                    capsize=3,
                    color=colors[metric_name],
                    label=metric_name if metric_name not in labeled else None,
                )
                labeled.add(metric_name)
        axis.set_title(title)
        axis.set_xticks(range(len(AGENT_SLOTS)), [slot[1] for slot in AGENT_SLOTS])
        axis.tick_params(axis="x", labelrotation=15, labelsize=8)
        axis.set_xlim(-0.5, len(AGENT_SLOTS) - 0.5)
        axis.set_ylim(0, 1)
        handles, labels = axis.get_legend_handles_labels()
        if handles:
            axis.legend(handles, labels)
    axes[0].set_ylabel("Rate")
    figure.tight_layout()
    figure.savefig(path, metadata={"Software": None})
    plt.close(figure)


def build_report(
    run_dirs: dict[str, Path | None], out_dir: Path
) -> tuple[Path, Path]:
    runs: dict[str, tuple[list[EpisodeResult], dict] | None] = {}
    for key, _, expected_agent in AGENT_SLOTS:
        run_dir = run_dirs.get(key)
        if (
            run_dir is None
            or not run_dir.exists()
            or not any((run_dir / "episodes").glob("*.json"))
        ):
            runs[key] = None
        else:
            runs[key] = load_run(run_dir, expected_agent)

    out_dir.mkdir(parents=True, exist_ok=True)
    markdown_path = out_dir / "results.md"
    figure_path = out_dir / "results.png"
    runner.write_atomic(markdown_path, render_markdown(runs))
    write_figure(runs, figure_path)
    return markdown_path, figure_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="mirage.evaluation.report")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--claude", type=Path)
    parser.add_argument("--good-scientist", type=Path)
    parser.add_argument("--passive-bayes", type=Path)
    args = parser.parse_args(argv)
    run_dirs = {
        "claude": args.claude,
        "good_scientist": args.good_scientist,
        "passive_bayes": args.passive_bayes,
    }
    try:
        build_report(run_dirs, args.out)
    except (ValueError, FileNotFoundError) as err:
        print(f"report: {err}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
